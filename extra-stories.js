function validateStoryLibrary(){
  const allTemplates=[...MALE_STORY_TEMPLATES,...FEMALE_STORY_TEMPLATES];
  const assert=(condition,message)=>{if(!condition)throw new Error("角色故事庫驗證失敗："+message)};
  assert(MALE_STORY_TEMPLATES.length===100,"男性故事必須為 100 則");
  assert(FEMALE_STORY_TEMPLATES.length===100,"女性故事必須為 100 則");
  assert(allTemplates.every(template=>template.title&&template.story&&template.story.length>=30),"每則故事必須有足夠完整的標題與正文");
  assert(new Set(allTemplates.map(template=>template.title)).size===200,"故事標題不可重複");
  assert(new Set(allTemplates.map(template=>template.story)).size===200,"故事正文不可重複");
  assert(Object.keys(MALE_INFECTION_SOURCES).length===30,"男性感染背景必須為 30 則");
  assert(Object.keys(FEMALE_INFECTION_SOURCES).length===30,"女性感染背景必須為 30 則");
  const allInfectionSources=[...Object.values(MALE_INFECTION_SOURCES),...Object.values(FEMALE_INFECTION_SOURCES)];
  assert(new Set(allInfectionSources).size===60,"感染背景不可重複或只替換性別代名詞");
  assert(PARTY_PEOPLE.length===200,"人物池必須為 200 位");
  assert(new Set(PARTY_PEOPLE.map(person=>person.id)).size===200,"人物識別碼不可重複");
  assert(new Set(PARTY_PEOPLE.map(person=>person.gender+person.name)).size===200,"人物姓名不可重複");
  assert(PARTY_PEOPLE.every(person=>person.story&&person.title&&person.infected===Boolean(person.infectionSource)),"每位人物都必須正確綁定故事與健康設定");
  const venueProfiles=PARTY_PEOPLE.filter(person=>person.venueCameo);
  assert(venueProfiles.length===12,"夜生活場景彩蛋必須為 12 則");
  assert(venueProfiles.every(person=>!person.infected&&!person.infectionSource),"真實店名不可與感染或健康風險設定綁定");
  assert(new Set(venueProfiles.map(person=>person.venueCameo)).size===12,"夜生活場景彩蛋不可重複");
}

